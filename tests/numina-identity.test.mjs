test('current NUMINA runners are preserved without freezing placement',()=>{
  const policy=JSON.parse(readFileSync(new URL('../config/numina-runners.json',import.meta.url),'utf8'));
  assert.equal(policy.identity,'NUMINA');
  assert.equal(policy.hostIdentity,'NUMINA');
  assert.equal(policy.runnerIdentity,'NUMINA');
  assert.equal(policy.allRunnerIdentities,'NUMINA');
  assert.equal(policy.runnerTarget,'NUMINA');
  assert.equal(policy.selfHostedPolicy,'preserve_existing');
  assert.equal(policy.futureRunnerPolicy,'deny');
  assert.equal(policy.invariants.preserveCurrentRunners,true);
  assert.equal(policy.invariants.preserveExistingSelfHostedRunners,true);
  assert.equal(policy.invariants.denyFutureRunners,true);
  assert.equal(policy.invariants.allRunnersAreNumina,true);
  assert.equal(policy.invariants.hostIsNumina,true);
  assert.equal(policy.invariants.runnerPlacementFrozen,false);
  assert.equal(policy.invariants.floatingHostedLinuxLabelsDenied,true);
  assert.equal(policy.executionTargets.hostedLinuxPolicy.pinnedTarget,'ubuntu-24.04');
  assert.deepEqual(policy.executionTargets.hostedLinuxPolicy.floatingLabelsDenied,['ubuntu-latest']);
  assert.equal(policy.executionTargets.hostedLinuxPolicy.migrationNotice.migrationBegins,'2026-10-19');
  assert.equal(policy.executionTargets.hostedLinuxPolicy.migrationNotice.target,'ubuntu-26');
  const workflowsUrl=new URL('../.github/workflows/',import.meta.url);
  assert.deepEqual(policy.executionTargets.workflowOverrides,{'numina-release.yml':'ubuntu-24.04','numina.yml':'ubuntu-24.04','verify-provider-observations.yml':'ubuntu-24.04','numina-android-release.yml':'ubuntu-24.04','numina-ios-signing.yml':'macos-latest','publish-sites-control-source.yml':'ubuntu-24.04','verify-root-vercel.yml':'ubuntu-24.04','align-native-treasury-500t.yml':'ubuntu-24.04','check-sites-control-origin.yml':'ubuntu-24.04','deploy-nusd-contracts.yml':'ubuntu-24.04','diagnose-control-auth.yml':'ubuntu-24.04','ibm-quantum-hardware.yml':'ubuntu-24.04','ibm-quantum-smoke.yml':'ubuntu-24.04','initiate-treasury-aggregate-model.yml':'ubuntu-24.04','verify-workflow-pins.yml':'ubuntu-24.04','sync-control-key-pin.yml':'ubuntu-24.04','verify-nusd-production.yml':'ubuntu-24.04'});
  assert.deepEqual(policy.executionTargets.workflowTargetSets,{'numina-mobile-release-build.yml':['ubuntu-24.04','macos-latest'],'numina-mobile-store-distribution.yml':['ubuntu-24.04','macos-latest'],'numina-site-builder.yml':['ubuntu-24.04','ubuntu-24.04'],'numina-nusd-runtime-builder.yml':['ubuntu-24.04','ubuntu-24.04']});
  assert.equal(policy.executionTargets.default,'NUMINA');
  let declarations=0;
  for(const name of readdirSync(workflowsUrl).filter(name=>/\.ya?ml$/i.test(name))){
    const content=readFileSync(new URL(name,workflowsUrl),'utf8');
    const targets=[...content.matchAll(/^\s*runs-on:\s*(.+?)\s*(?:#.*)?$/gm)].map(match=>match[1].trim().replace(/^['"]|['"]$/g,''));
    declarations+=targets.length;
    const targetSet=policy.executionTargets.workflowTargetSets?.[name];
    if(targetSet)assert.deepEqual([...targets].sort(),[...targetSet].sort(),name+' execution target set must match the preserved policy');
    else {
      const expected=policy.executionTargets.workflowOverrides[name]??policy.executionTargets.default;
      for(const target of targets)assert.equal(target,expected,name+' execution target must match the preserved policy');
    }
  }
  assert.equal(declarations,policy.preservedRunnerCount,'runner count must remain preserved with no future additions');
});


test('NUMINA activation preserves existing runner only',()=>{
  const pkg=JSON.parse(readFileSync(new URL('../package.json',import.meta.url),'utf8'));
  assert.equal(pkg.scripts['runner:activate'],'powershell -NoProfile -ExecutionPolicy Bypass -File scripts/activate-numina-runner.ps1');
  assert.equal(pkg.scripts['runner:status'],'powershell -NoProfile -ExecutionPolicy Bypass -File scripts/activate-numina-runner.ps1 -StatusOnly');
  const activation=readFileSync(new URL('../scripts/activate-numina-runner.ps1',import.meta.url),'utf8');
  assert.match(activation,/NUMINA_RUNNER_NOT_REGISTERED_FUTURE_RUNNER_CREATION_DENIED/);
  assert.doesNotMatch(activation,/registration-token/i);
  assert.doesNotMatch(activation,/config\.cmd/i);
});
