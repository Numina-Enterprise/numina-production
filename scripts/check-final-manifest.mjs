import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const json=p=>JSON.parse(readFileSync(p,'utf8'));
const manifest=json('public/final-manifest.json');
const buildBytes=readFileSync('public/final-build.json');
const manifestBytes=readFileSync('public/final-manifest.json');
const buildSha256=createHash('sha256').update(buildBytes).digest('hex');
const manifestSha256=createHash('sha256').update(manifestBytes).digest('hex');
const ids=manifest.universalPair.sourceIds;
const artifacts=['public/final-build.json','public/final-manifest.json'];
const routes=['/final-build.json','/final-manifest.json'];
const frontierIds=['L1','L2','L3','L4','L5','L6','L7'];
assert.equal(ids.length,1);
assert.equal(manifest.schema,'numina.final-manifest.v1');
assert.equal(manifest.identity,'NUMINA');
assert.equal(manifest.status,'FINAL');
assert.equal(manifest.frontierId,'996f0ce7cc8cc5809969c6aaf5188d5c3a9a6332dbe5fd231cca974152a115fa');
assert.equal(manifest.canonicalSha256,'996f0ce7cc8cc5809969c6aaf5188d5c3a9a6332dbe5fd231cca974152a115fa');
assert.equal(manifest.finalBuild.sha256,'996f0ce7cc8cc5809969c6aaf5188d5c3a9a6332dbe5fd231cca974152a115fa');
assert.equal(manifest.finalBuild.currentContentSha256,buildSha256);
assert.equal(manifest.universalPair.matrix,'1x2');
assert.equal(manifest.universalPair.environmentCount,1);
assert.equal(manifest.universalPair.bindingCount,2);
assert.deepEqual(manifest.universalPair.environments,['FRONTIER']);
assert.equal(manifest.environmentCount,1);
assert.deepEqual(manifest.currentEnvironments,['FRONTIER']);
assert.equal(manifest.environmentBindings.length,2);
assert.deepEqual(manifest.currentPush,{environment:'FRONTIER',status:'FINAL',gate:'CLOSED',futureAdvancementAllowed:true});

const frontier=manifest.architectureFrontier;
assert.equal(frontier.schema,'numina.architecture-frontier.v3');
assert.equal(frontier.frontierLayerCount,7);
assert.deepEqual(frontier.frontierLayers.map(x=>x.id),frontierIds);
assert.equal(frontier.gate,'CLOSED');
assert.equal(frontier.advancement,false);
assert.equal(frontier.currentPushEnvironment,'FRONTIER');
assert.equal(frontier.futureAdvancementAllowed,true);
const build=json('public/final-build.json');
assert.deepEqual(manifest.environmentBindings,build.environmentBindings);
assert.deepEqual(manifest.universalPair.sourceIds,build.universalPair.sourceIds);
const pkg=json('package.json');
assert.equal(pkg.numina.finalBuildManifest.sha256,'996f0ce7cc8cc5809969c6aaf5188d5c3a9a6332dbe5fd231cca974152a115fa');
assert.equal(pkg.numina.finalBuildManifest.currentContentSha256,buildSha256);
assert.equal(pkg.numina.finalManifest.sha256,'c9300f87f0ccfe1f2e2e132ecfa9e5de9a23f144dcdfa682849fe6f7bcc09b63');
assert.equal(pkg.numina.finalManifest.currentContentSha256,manifestSha256);
assert.deepEqual(manifest.immutableReleaseHashes,{finalBuildSha256:'996f0ce7cc8cc5809969c6aaf5188d5c3a9a6332dbe5fd231cca974152a115fa',finalManifestSha256:'c9300f87f0ccfe1f2e2e132ecfa9e5de9a23f144dcdfa682849fe6f7bcc09b63'});
console.log('NUMINA Universal Pair: 1 source ID = 2 FRONTIER bindings; frontier-only push verified.');
