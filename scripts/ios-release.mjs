// Numina iOS source identity. No network, signing, or application execution.
import {readFileSync, readdirSync, lstatSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const ROOT = fileURLToPath(new URL('../', import.meta.url));
const fail = message => { throw new Error(message); };
const capture = (text, expression, label) => text.match(expression)?.[1]?.trim() ?? fail('MISSING_' + label);
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
export function deriveIOSIdentity({pkg, architecture, runtimeText, native, policy, settings}) {
  if (pkg.name !== 'numina-singular-control' || !/^\d+\.\d+\.\d+$/.test(pkg.version)) fail('APPLICATION_IDENTITY_INVALID');
  const runtime = capture(runtimeText, /RUNTIME_VERSION = '([^']+)'/, 'RUNTIME_VERSION');
  const frozenRoot = capture(runtimeText, /"frozen_core_manifest_root": "([a-f0-9]{64})"/, 'FROZEN_ROOT');
  const core = capture(runtimeText, /"core_version": "([^"\r\n]+)"/, 'CORE_VERSION');
  const version = capture(settings, /^MARKETING_VERSION = ([^\r\n]+)$/m, 'IOS_VERSION');
  const build = capture(settings, /^CURRENT_PROJECT_VERSION = (\d+)$/m, 'IOS_BUILD');
  const bundle = capture(settings, /^PRODUCT_BUNDLE_IDENTIFIER = ([^\r\n]+)$/m, 'IOS_BUNDLE');
  const deploymentTarget = capture(settings, /^IPHONEOS_DEPLOYMENT_TARGET = ([^\r\n]+)$/m, 'IOS_TARGET');
  const manifest = '/v' + pkg.version.split('.')[0] + '/release/manifest';
  if (version !== pkg.version || native.applicationVersion !== version || architecture.applicationVersion !== version || architecture.frontierVersion !== version) fail('APPLICATION_VERSION_MISMATCH');
  if (runtime !== architecture.runtime || runtime !== '1.9.0-rc27' || architecture.pendingRuntimeMigration !== null) fail('RUNTIME_PIN_MISMATCH');
  if (architecture.applicationManifest !== manifest) fail('APPLICATION_MANIFEST_MISMATCH');
  if (bundle !== native.proposedPackageIdentity || bundle !== policy.packageIdentity) fail('BUNDLE_IDENTITY_MISMATCH');
  if (!Number.isSafeInteger(Number(build)) || Number(build) < 1 || Number(build) < native.ios.binaryVersionCode) fail('IOS_BUILD_REGRESSION');
  if (native.hostedWorkspace !== 'https://numinalabs.xyz/app') fail('APPLICATION_ORIGIN_MISMATCH');
  return {schema:'numina.ios-source-identity.v1', applicationVersion:version, buildNumber:Number(build),
    bundleIdentifier:bundle, deploymentTarget, runtimeVersion:runtime, coreVersion:core, frozenCoreRoot:frozenRoot,
    applicationOrigin:'https://numinalabs.xyz', applicationManifest:manifest, telemetryEndpoint:'/api/ops/v1/telemetry',
    runtimePanel:'/frontier#runtime-metrics', minimumXcodeMajor:26, minimumIOSSDKMajor:26,
    historicalBinaryVersion:native.ios.binaryApplicationVersion, historicalBinaryBuild:native.ios.binaryVersionCode,
    nativeCompilationEstablished:false, signed:false, storeSubmitted:false};
}
export function loadIOSIdentity(root=ROOT) {
  const read = path => readFileSync(resolve(root,path),'utf8');
  const pkg = JSON.parse(read('package.json'));
  return deriveIOSIdentity({pkg, architecture:JSON.parse(read('config/numina-architecture.json')),
    runtimeText:read('public/runtime-contract.js'), native:JSON.parse(read('docs/native-package-record-v'+pkg.version.split('.')[0]+'.json')),
    policy:JSON.parse(read('mobile/signing/distribution-policy.json')), settings:read('mobile/ios/Configuration/Numina.xcconfig')});
}
export function renderIOSRelease(identity) {
  return '// Generated by node scripts/ios-release.mjs sync; do not edit.\n'
    + 'NUMINA_RUNTIME_VERSION = ' + identity.runtimeVersion + '\n'
    + 'NUMINA_CORE_VERSION = ' + identity.coreVersion + '\n'
    + 'NUMINA_FROZEN_CORE_ROOT = ' + identity.frozenCoreRoot + '\n'
    + 'NUMINA_APPLICATION_MANIFEST = ' + identity.applicationManifest + '\n'
    + 'NUMINA_TELEMETRY_ENDPOINT = ' + identity.telemetryEndpoint + '\n';
}
export function checkIOSRelease(root=ROOT) {
  const identity = loadIOSIdentity(root), read = path => readFileSync(resolve(root,path),'utf8').replaceAll('\r\n','\n');
  if (read('mobile/ios/Configuration/NuminaRelease.xcconfig') !== renderIOSRelease(identity)) fail('IOS_GENERATED_RELEASE_STALE');
  if (!read('mobile/ios/Configuration/Numina.xcconfig').includes('#include "NuminaRelease.xcconfig"')) fail('IOS_RELEASE_INCLUDE_MISSING');
  const plist = read('mobile/ios/Numina/Info.plist');
  for (const [key, setting] of Object.entries({NuminaRuntimeVersion:'NUMINA_RUNTIME_VERSION', NuminaCoreVersion:'NUMINA_CORE_VERSION',
    NuminaFrozenCoreRoot:'NUMINA_FROZEN_CORE_ROOT', NuminaApplicationManifest:'NUMINA_APPLICATION_MANIFEST', NuminaTelemetryEndpoint:'NUMINA_TELEMETRY_ENDPOINT'})) {
    if (!plist.includes('<key>'+key+'</key><string>$('+setting+')</string>')) fail('IOS_BUNDLE_BINDING_MISSING_' + key);
  }
  const config = read('mobile/ios/Numina/AppConfiguration.swift');
  if (!config.includes('static let origin = URL(string: "'+identity.applicationOrigin+'")!')) fail('IOS_ORIGIN_MISMATCH');
  if (!config.includes('components.fragment = "runtime-metrics"')) fail('IOS_RUNTIME_PANEL_MISMATCH');
  return identity;
}
export function iosInputSnapshot(root=ROOT) {
  const paths = ['package.json','config/numina-architecture.json','public/runtime-contract.js',
    'mobile/signing/distribution-policy.json','mobile/signing/numina-ios-distribution.csr',
    'scripts/ios-release.mjs','scripts/package-ios-source.py','scripts/sign-ios-release.py',
    '.github/workflows/numina-ios-branch-build.yml','.github/workflows/numina-native-packages.yml','.github/workflows/numina-ios-signing.yml'];
  const excluded = new Set(['build','DerivedData','.git','.DS_Store','signing']);
  function walk(directory) {
    for (const name of readdirSync(resolve(root,directory)).sort()) {
      if (excluded.has(name)) continue;
      const path = directory+'/'+name, stat = lstatSync(resolve(root,path));
      if (stat.isSymbolicLink()) fail('IOS_INPUT_SYMLINK');
      if (stat.isDirectory()) walk(path);
      else if (stat.isFile()) {
        if (/\.(?:p12|key|mobileprovision|p8)$/i.test(name) || name.startsWith('.env')) fail('IOS_PRIVATE_MATERIAL_IN_SOURCE');
        if (stat.size > 8*1024*1024) fail('IOS_INPUT_TOO_LARGE');
        paths.push(path);
      }
    }
  }
  walk('mobile/ios');
  const inputs = [...new Set(paths)].sort().map(path => {
    const raw=readFileSync(resolve(root,path));
    const bytes=/\.(?:png|jpg|jpeg|ico)$/i.test(path)?raw:Buffer.from(raw.toString('utf8').replaceAll('\r\n','\n'));
    return {path,bytes:bytes.length,sha256:sha(bytes)};
  });
  return {sha256:sha(JSON.stringify(inputs)),inputs,scope:'scoped_current_source_not_signed_provenance',textNormalization:'utf8_lf_binary_unchanged'};
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const mode=process.argv[2] || 'check';
    if (!['check','sync','identity'].includes(mode) || process.argv.length>3) fail('USAGE: ios-release.mjs [check|sync|identity]');
    if (mode==='sync') writeFileSync(resolve(ROOT,'mobile/ios/Configuration/NuminaRelease.xcconfig'),renderIOSRelease(loadIOSIdentity()));
    const identity=checkIOSRelease();
    console.log(JSON.stringify(mode==='identity'?{...identity,sourceInputs:iosInputSnapshot()}:identity,null,2));
  } catch(error) { console.error(error.message); process.exitCode=1; }
}
